#!/usr/bin/env python3
"""Build the 4x4 finite-t' U-only/V-only rho_G color-plot grid.

Inputs are the eta=0.05 spectra-and-roots NPZ files generated by
``generate_eta005_other_parameter_colorplots.py``.  The four rows are
U-only t'=-0.25, U-only t'=-0.4, V-only t'=-0.25, and V-only t'=-0.4.
Each panel overlays the clean Re G=0 branch in white and uses the exact
nonuniform Gamma-X-M-Gamma path coordinate.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from reproduce_luttinger_figures import centers_to_edges  # noqa: E402


DATE_TAG = "20260802"
DATA_DIR = (
    ROOT
    / "data/Gcalpath/luttinger_surface_eta0p05_uonly_vonly_finite_tprime_20260802"
)
FIG_DIR = ROOT / "figures/luttinger_eta0p05_uonly_vonly_finite_tprime_20260802"
FIGURE_STEM = FIG_DIR / "rhoG_LS_uonly_vonly_finite_tprime_4x4_eta0p05"
MANIFEST = ROOT / "results/uonly_vonly_finite_tprime_colorplot_manifest_20260802.json"

U_VALUES = (8, 12, 20, 40)
V_VALUES = (2, 5, 8, 12)
ROW_SPECS = (
    ("U-only", -0.25, U_VALUES),
    ("U-only", -0.4, U_VALUES),
    ("V-only", -0.25, V_VALUES),
    ("V-only", -0.4, V_VALUES),
)


def tp_stem(tp: float) -> str:
    return str(tp).replace("-", "n").replace(".", "p")


def source_path(branch: str, interaction: int, tp: float) -> Path:
    U, V = (interaction, 0) if branch == "U-only" else (0, interaction)
    return DATA_DIR / (
        f"rhoG_LS_U{U}_V{V}_tp{tp_stem(tp)}_eta0p05_spectra_and_roots.npz"
    )


def individual_stem(branch: str, interaction: int, tp: float) -> Path:
    U, V = (interaction, 0) if branch == "U-only" else (0, interaction)
    return FIG_DIR / f"rhoG_LS_U{U}_V{V}_tp{tp_stem(tp)}_eta0p05"


def load_panel(branch: str, interaction: int, tp: float) -> dict:
    path = source_path(branch, interaction, tp)
    if not path.is_file():
        raise FileNotFoundError(path)
    with np.load(path) as data:
        panel = {
            "source": path,
            "omega": np.asarray(data["omega"], dtype=float).copy(),
            "x": np.asarray(data["x_path"], dtype=float).copy(),
            "k_path": np.asarray(data["k_path"], dtype=int).copy(),
            "rho": np.asarray(data["rho_G"], dtype=float).copy(),
            "root": np.asarray(data["omega_root"], dtype=float).copy(),
            "eta": float(np.asarray(data["eta"]).item()),
            "U": float(np.asarray(data["U"]).item()),
            "V": float(np.asarray(data["V"]).item()),
            "tp": float(np.asarray(data["tp"]).item()),
            "ylim": float(np.asarray(data["ylim"]).item()),
        }
    expected_U, expected_V = (
        (float(interaction), 0.0) if branch == "U-only" else (0.0, float(interaction))
    )
    if not (
        np.isclose(panel["eta"], 0.05)
        and np.isclose(panel["U"], expected_U)
        and np.isclose(panel["V"], expected_V)
        and np.isclose(panel["tp"], tp)
    ):
        raise ValueError(f"Metadata mismatch in {path}")
    if panel["rho"].shape != (121, panel["omega"].size):
        raise ValueError(f"Unexpected rho_G shape in {path}: {panel['rho'].shape}")
    if panel["root"].shape != (121,) or not np.isfinite(panel["root"]).all():
        raise ValueError(f"Incomplete root overlay in {path}")
    if panel["x"].shape != (121,) or panel["k_path"].shape != (121, 2):
        raise ValueError(f"Unexpected path arrays in {path}")
    return panel


def main() -> None:
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    panels = {
        (branch, tp, value): load_panel(branch, value, tp)
        for branch, tp, values in ROW_SPECS
        for value in values
    }
    # Use one vertical window per interaction column within each two-row branch
    # block, so t'=-0.25 and -0.4 can be compared without axis rescaling.
    u_ylims = {
        U: max(panels[("U-only", tp, U)]["ylim"] for tp in (-0.25, -0.4))
        for U in U_VALUES
    }
    v_ylims = {
        V: max(panels[("V-only", tp, V)]["ylim"] for tp in (-0.25, -0.4))
        for V in V_VALUES
    }

    style = {
        "font.family": "Arial",
        "font.size": 9.0,
        "axes.labelsize": 10.0,
        "axes.titlesize": 10.5,
        "xtick.labelsize": 8.2,
        "ytick.labelsize": 8.2,
        "axes.linewidth": 0.8,
        "pdf.fonttype": 42,
        "ps.fonttype": 42,
    }
    with plt.rc_context(style):
        fig, axes = plt.subplots(4, 4, figsize=(13.1, 11.3), squeeze=False)
        fig.subplots_adjust(
            left=0.09,
            right=0.985,
            bottom=0.105,
            top=0.965,
            wspace=0.20,
            hspace=0.33,
        )
        cmap = plt.get_cmap("rainbow").copy()
        cmap.set_bad(color="0.35", alpha=0.45)
        panel_index = 0
        image = None
        for row_index, (branch, tp, values) in enumerate(ROW_SPECS):
            for col_index, interaction in enumerate(values):
                ax = axes[row_index, col_index]
                data = panels[(branch, tp, interaction)]
                ylim = u_ylims[interaction] if branch == "U-only" else v_ylims[interaction]
                mask = np.abs(data["omega"]) <= ylim
                image = ax.pcolormesh(
                    centers_to_edges(data["x"]),
                    centers_to_edges(data["omega"][mask]),
                    np.maximum(data["rho"][:, mask], 0.0).T,
                    shading="auto",
                    cmap=cmap,
                    vmin=0.0,
                    vmax=2.5,
                    rasterized=True,
                )
                ax.plot(data["x"], data["root"], color="white", lw=1.45)
                ax.axhline(0.0, color="black", ls="--", lw=0.75)
                for xpos in (data["x"][40], data["x"][80]):
                    ax.axvline(xpos, color="black", ls="--", lw=0.65, alpha=0.8)
                ax.set_xlim(data["x"][0], data["x"][-1])
                ax.set_ylim(-ylim, ylim)
                ax.set_xticks(
                    [data["x"][0], data["x"][40], data["x"][80], data["x"][120]]
                )
                if row_index in (1, 3):
                    ax.set_xticklabels([r"$\Gamma$", "X", "M", r"$\Gamma$"])
                else:
                    ax.set_xticklabels([])
                if col_index == 0:
                    ax.set_ylabel(r"$\omega/t$")
                title_symbol = "U" if branch == "U-only" else "V"
                if row_index in (0, 2):
                    ax.set_title(rf"${title_symbol}={interaction}$")
                ax.text(
                    0.025,
                    0.965,
                    f"({chr(ord('a') + panel_index)})",
                    transform=ax.transAxes,
                    ha="left",
                    va="top",
                    color="white",
                    fontsize=9.2,
                    fontweight="bold",
                )
                panel_index += 1
            axes[row_index, 0].text(
                -0.34,
                0.5,
                f"{branch}\n" + rf"$t'={tp:g}t$",
                transform=axes[row_index, 0].transAxes,
                ha="center",
                va="center",
                rotation=90,
                fontsize=10.0,
            )
        assert image is not None
        cbar_ax = fig.add_axes([0.26, 0.038, 0.56, 0.018])
        cbar = fig.colorbar(image, cax=cbar_ax, orientation="horizontal")
        cbar.set_label(r"$\rho_G(\mathbf{k},\omega)$", labelpad=2)
        cbar.set_ticks(np.linspace(0.0, 2.5, 6))

        pdf = FIGURE_STEM.with_suffix(".pdf")
        png = FIGURE_STEM.with_suffix(".png")
        fig.savefig(pdf, bbox_inches="tight")
        fig.savefig(png, dpi=260, bbox_inches="tight")
        plt.close(fig)

    if pdf.read_bytes()[:4] != b"%PDF":
        raise RuntimeError(f"Invalid PDF: {pdf}")
    if png.stat().st_size == 0:
        raise RuntimeError(f"Empty PNG: {png}")

    entries = []
    for branch, tp, values in ROW_SPECS:
        for interaction in values:
            data = panels[(branch, tp, interaction)]
            individual = individual_stem(branch, interaction, tp)
            individual_pdf = individual.with_suffix(".pdf")
            individual_png = individual.with_suffix(".png")
            if not individual_pdf.is_file() or not individual_png.is_file():
                raise FileNotFoundError(f"Missing individual plot for {branch}, {interaction}, {tp}")
            entries.append(
                {
                    "branch": branch,
                    "U": data["U"],
                    "V": data["V"],
                    "tprime": data["tp"],
                    "eta": data["eta"],
                    "rho_shape": list(data["rho"].shape),
                    "root_count": int(np.isfinite(data["root"]).sum()),
                    "source_npz": str(data["source"].relative_to(ROOT)),
                    "individual_pdf": str(individual_pdf.relative_to(ROOT)),
                    "individual_png": str(individual_png.relative_to(ROOT)),
                }
            )
    manifest = {
        "date_tag": DATE_TAG,
        "eta": 0.05,
        "path": "Gamma-X-M-Gamma, 121 plotted rows / 120 unique momenta",
        "color_scale": {"vmin": 0.0, "vmax": 2.5},
        "root_overlay": "white ReG=0 clean branch",
        "group_count": len(entries),
        "all_groups_have_121_roots": all(item["root_count"] == 121 for item in entries),
        "entries": entries,
        "combined_pdf": str(pdf.relative_to(ROOT)),
        "combined_png": str(png.relative_to(ROOT)),
    }
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
