FILENAME_RE = re.compile(
    r"L(?P<Lx>\d+)x(?P<Ly>\d+)Nup(?P<Nup>\d+)Ndn(?P<Ndn>\d+)"
    r"U(?P<U>[-+0-9.eE]+)V(?P<V>[-+0-9.eE]+)tp(?P<tp>[-+0-9.eE]+)"
    r"f(?P<kx>\d+)x(?P<ky>\d+)Q(?P<Qx>\d+)x(?P<Qy>\d+)_E0D\.dat"
)


