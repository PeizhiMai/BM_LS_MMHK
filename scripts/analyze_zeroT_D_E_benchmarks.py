def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def parse_value(text: str):
    try:
        return float(text)
    except ValueError:
        return text.strip()


def parse_file(path: Path) -> dict:
    match = FILENAME_RE.fullmatch(path.name)
    if not match:
        raise ValueError(f"Unexpected filename: {path.name}")
    row = {
        key: (float(value) if key in {"U", "V", "tp"} else int(value))
        for key, value in match.groupdict().items()
    }
    for line in path.read_text(errors="replace").splitlines():
        fields = line.split(None, 1)
        if len(fields) == 2:
            row[fields[0]] = parse_value(fields[1])
    row["filename"] = path.name
    row["size_bytes"] = path.stat().st_size
    row["sha256"] = sha256(path)
    required = {"E0", "E0_per_site", "D", "status", "max_iterations", "seed"}
    missing = required.difference(row)
    if missing:
        raise ValueError(f"{path.name}: missing fields {sorted(missing)}")
    if row["status"] != "COMPLETE":
        raise ValueError(f"{path.name}: status is {row['status']!r}")
    if int(round(float(row["max_iterations"]))) != 10000:
        raise ValueError(f"{path.name}: max_iterations != 10000")
    if not (0 <= row["kx"] <= row["ky"] <= 40):
        raise ValueError(f"{path.name}: point is outside the symmetry wedge")
    if row["Nup"] != 8 or row["Ndn"] != 8 or row["Qx"] != 0 or row["Qy"] != 0:
        raise ValueError(f"{path.name}: unexpected particle or Q sector")
    if not math.isclose(float(row["tp"]), 0.0, abs_tol=1e-14):
        raise ValueError(f"{path.name}: expected tp=0")
    if not math.isclose(float(row["E0_per_site"]), float(row["E0"]) / NSITES, abs_tol=1e-12):
        raise ValueError(f"{path.name}: inconsistent E0_per_site")
    wx = 0.5 if row["kx"] in {0, 40} else 1.0
    wy = 0.5 if row["ky"] in {0, 40} else 1.0
    symmetry = 1.0 if row["kx"] == row["ky"] else 2.0
    row["quadrature_weight"] = wx * wy * symmetry
    return row


def weighted_mean(values, weights) -> float:
    values = np.asarray(values, dtype=float)
    weights = np.asarray(weights, dtype=float)
    return float(np.sum(values * weights) / np.sum(weights))


def weighted_std(values, weights) -> float:
    values = np.asarray(values, dtype=float)
    weights = np.asarray(weights, dtype=float)
    mean = weighted_mean(values, weights)
    return float(np.sqrt(np.sum(weights * (values - mean) ** 2) / np.sum(weights)))


def nested_average(group: pd.DataFrame, column: str, spacing: int) -> tuple[float, float, int]:
    nested = group[(group["kx"] % spacing == 0) & (group["ky"] % spacing == 0)].copy()
    # The same endpoint/symmetry formula gives unnormalized weights for each
    # nested trapezoidal grid; normalization is therefore its own weight sum.
    return (
        weighted_mean(nested[column], nested["quadrature_weight"]),
        float(nested["quadrature_weight"].sum()),
        int(len(nested)),
    )


def exact_spinless_obc_energy(L: int = 10, particles: int = 50) -> tuple[float, float]:
    levels = []
    for nx in range(1, L + 1):
        for ny in range(1, L + 1):
            levels.append(-2.0 * (math.cos(math.pi * nx / (L + 1)) + math.cos(math.pi * ny / (L + 1))))
    total = float(np.sum(np.sort(levels)[:particles]))
    return total, total / (L * L)


def exact_free_16mmhk_grid_energy(spacing: int = 1) -> float:
    """Exact free spinful energy on the same mixed-momentum quadrature.

    For each sector momentum f, fill the eight lowest of the 16 one-body
    orbitals K+f for each spin and then apply the same symmetry/trapezoidal
    weights as the interacting calculation.
    """

    energies = []
    weights = []
    for kx in range(0, 41, spacing):
        for ky in range(kx, 41, spacing):
            fx = kx * math.pi / 40.0 + 0.00001
            fy = ky * math.pi / 40.0 + 0.00001
            levels = [
                -2.0
                * (
                    math.cos(2.0 * math.pi * nx / 4.0 + fx)
                    + math.cos(2.0 * math.pi * ny / 4.0 + fy)
                )
                for nx in range(4)
                for ny in range(4)
            ]
            energies.append(2.0 * sum(sorted(levels)[:8]) / NSITES)
            wx = 0.5 if kx in {0, 40} else 1.0
            wy = 0.5 if ky in {0, 40} else 1.0
            weights.append(wx * wy * (1.0 if kx == ky else 2.0))
    return weighted_mean(energies, weights)


def load_rows(raw_dir: Path) -> pd.DataFrame:
    files = sorted(raw_dir.rglob("*_E0D.dat"))
    if not files:
        raise FileNotFoundError(f"No *_E0D.dat files found under {raw_dir}")
    rows = [parse_file(path) for path in files]
    frame = pd.DataFrame(rows)
    duplicated = frame.duplicated(["U", "V", "kx", "ky"], keep=False)
    if duplicated.any():
        names = frame.loc[duplicated, "filename"].tolist()[:20]
        raise ValueError(f"Duplicate (U,V,kx,ky) rows: {names}")
    return frame.sort_values(["U", "V", "kx", "ky"]).reset_index(drop=True)


def summarize(frame: pd.DataFrame, allow_incomplete: bool) -> pd.DataFrame:
    expected = {(float(U), float(V)) for U, V in CALCULATED_SETS}
    observed = {(float(U), float(V)) for U, V in frame[["U", "V"]].drop_duplicates().itertuples(index=False)}
    extra = observed.difference(expected)
    if extra:
        raise ValueError(f"Unexpected interaction sets: {sorted(extra)}")
    missing_sets = expected.difference(observed)
    if missing_sets and not allow_incomplete:
        raise ValueError(f"Missing interaction sets: {sorted(missing_sets)}")

    output = []
    for U, V in CALCULATED_SETS:
        group = frame[np.isclose(frame["U"], U) & np.isclose(frame["V"], V)].copy()
        if group.empty:
            output.append(
                {
                    "U_over_t": U,
                    "V_over_t": V,
                    "n_rows": 0,
                    "complete_fraction": 0.0,
                    "quadrature_weight": 0.0,
                    "status": "MISSING",
                }
            )
            continue
        nrows = int(len(group))
        total_weight = float(group["quadrature_weight"].sum())
        complete = nrows == EXPECTED_ROWS and math.isclose(total_weight, EXPECTED_WEIGHT, abs_tol=1e-12)
        if not complete and not allow_incomplete:
            raise ValueError(
                f"(U,V)=({U:g},{V:g}) has {nrows}/{EXPECTED_ROWS} rows and "
                f"weight {total_weight:g}/{EXPECTED_WEIGHT:g}"
            )
        record = {
            "U_over_t": U,
            "V_over_t": V,
            "n_rows": nrows,
            "complete_fraction": nrows / EXPECTED_ROWS,
            "quadrature_weight": total_weight,
            "status": "COMPLETE" if complete else "INCOMPLETE",
            "calculation_source": "Lanczos_16MMHK_10000",
            "E0_per_site_mean": weighted_mean(group["E0_per_site"], group["quadrature_weight"]),
            "E0_per_site_sector_std": weighted_std(group["E0_per_site"], group["quadrature_weight"]),
            "D_mean": weighted_mean(group["D"], group["quadrature_weight"]),
            "D_sector_std": weighted_std(group["D"], group["quadrature_weight"]),
            "seed_unique": int(group["seed"].nunique()),
            "iterations_min": int(np.min(group["max_iterations"])),
            "iterations_max": int(np.max(group["max_iterations"])),
        }
        for spacing, label, expected_weight, expected_rows in [
            (2, "21", 400.0, 231),
            (4, "11", 100.0, 66),
        ]:
            e_nested, weight, rows = nested_average(group, "E0_per_site", spacing)
            d_nested, _, _ = nested_average(group, "D", spacing)
            record[f"nested_{label}_rows"] = rows
            record[f"nested_{label}_weight"] = weight
            record[f"E0_per_site_nested_{label}"] = e_nested
            record[f"E0_per_site_nested_{label}_minus_full"] = e_nested - record["E0_per_site_mean"]
            record[f"D_nested_{label}"] = d_nested
            record[f"D_nested_{label}_minus_full"] = d_nested - record["D_mean"]
            if complete and (rows != expected_rows or not math.isclose(weight, expected_weight, abs_tol=1e-12)):
                raise ValueError(f"Nested {label}-point grid failed for (U,V)=({U},{V})")
        output.append(record)
    return pd.DataFrame(output)


def add_analytic_free_baseline(summary: pd.DataFrame) -> pd.DataFrame:
    """Append the exactly known U=V=0 baseline without a Lanczos grid scan."""

    e41 = exact_free_16mmhk_grid_energy(1)
    e21 = exact_free_16mmhk_grid_energy(2)
    e11 = exact_free_16mmhk_grid_energy(4)
    free = {
        "U_over_t": 0.0,
        "V_over_t": 0.0,
        "n_rows": 0,
        "complete_fraction": 1.0,
        "quadrature_weight": EXPECTED_WEIGHT,
        "status": "COMPLETE",
        "calculation_source": "analytic_noninteracting_limit",
        "E0_per_site_mean": e41,
        "E0_per_site_sector_std": math.nan,
        "D_mean": 0.25,
        "D_sector_std": 0.0,
        "seed_unique": 0,
        "iterations_min": 0,
        "iterations_max": 0,
        "nested_21_rows": 0,
        "nested_21_weight": 400.0,
        "E0_per_site_nested_21": e21,
        "E0_per_site_nested_21_minus_full": e21 - e41,
        "D_nested_21": 0.25,
        "D_nested_21_minus_full": 0.0,
        "nested_11_rows": 0,
        "nested_11_weight": 100.0,
        "E0_per_site_nested_11": e11,
        "E0_per_site_nested_11_minus_full": e11 - e41,
        "D_nested_11": 0.25,
        "D_nested_11_minus_full": 0.0,
    }
    return (
        pd.concat([summary, pd.DataFrame([free])], ignore_index=True)
        .sort_values(["U_over_t", "V_over_t"])
        .reset_index(drop=True)
    )


def literature_series(literature: pd.DataFrame, reference_prefix: str, series: str | None = None) -> pd.DataFrame:
    selected = literature[literature["reference"].str.startswith(reference_prefix)].copy()
    if series is not None:
        selected = selected[selected["series"] == series].copy()
    return selected.sort_values(["U_over_t", "V_over_t"])


def build_comparisons(summary: pd.DataFrame, literature: pd.DataFrame) -> pd.DataFrame:
    records = []
    yao = literature_series(literature, "Yao et al.")
    for row in yao.itertuples(index=False):
        mmhk = summary[np.isclose(summary["U_over_t"], row.U_over_t) & np.isclose(summary["V_over_t"], row.V_over_t)]
        if mmhk.empty or mmhk.iloc[0]["status"] != "COMPLETE":
            continue
        mmhk_row = mmhk.iloc[0]
        delta = float(mmhk_row["D_mean"] - row.value)
        records.append(
            {
                "comparison": "Yao_D",
                "U_over_t": row.U_over_t,
                "V_over_t": row.V_over_t,
                "mmhk_model": "spinful V-extended 16-MMHK",
                "literature_model": row.model,
                "mmhk_value": mmhk_row["D_mean"],
                "literature_value": row.value,
                "literature_uncertainty": row.uncertainty,
                "absolute_difference": delta,
                "absolute_difference_magnitude": abs(delta),
                "percentage_difference": 100.0 * delta / row.value,
                "normalization": "D per site",
                "interpretation": "direct observable comparison",
            }
        )

    zhou = literature_series(literature, "Zhou et al.", "p=1 backflow")
    zhou_fpeps = literature_series(literature, "Zhou et al.", "fPEPS")
    exact_v0 = literature[literature["record_id"] == "exact_spinless_10x10_obc_E_V0"].iloc[0]
    zhou_primary = pd.concat(
        [
            pd.DataFrame(
                [
                    {
                        "V_over_t": float(exact_v0["V_over_t"]),
                        "value": float(exact_v0["value"]),
                        "method": exact_v0["method"],
                    }
                ]
            ),
            zhou[["V_over_t", "value", "method"]],
        ],
        ignore_index=True,
    ).sort_values("V_over_t")
    mmhk_v0 = summary[(np.isclose(summary["U_over_t"], 0.0)) & (np.isclose(summary["V_over_t"], 0.0))]
    if not mmhk_v0.empty and mmhk_v0.iloc[0]["status"] == "COMPLETE":
        spinful_density = 1.0
        spinless_density = 0.5
        mmhk_baseline_per_site = float(mmhk_v0.iloc[0]["E0_per_site_mean"])
        spinless_baseline_per_site = float(exact_v0["value"])
        mmhk_baseline_per_particle = mmhk_baseline_per_site / spinful_density
        spinless_baseline_per_particle = spinless_baseline_per_site / spinless_density
        for row in zhou_primary.itertuples(index=False):
            mmhk = summary[(np.isclose(summary["U_over_t"], 0.0)) & (np.isclose(summary["V_over_t"], row.V_over_t))]
            if mmhk.empty or mmhk.iloc[0]["status"] != "COMPLETE":
                continue
            e_spinful_per_site = float(mmhk.iloc[0]["E0_per_site_mean"])
            e_spinless_per_site = float(row.value)
            e_spinful_per_particle = e_spinful_per_site / spinful_density
            e_spinless_per_particle = e_spinless_per_site / spinless_density
            if math.isclose(float(row.V_over_t), 0.0, abs_tol=1e-14):
                e_fpeps_per_site = math.nan
            else:
                fpeps_match = zhou_fpeps[np.isclose(zhou_fpeps["V_over_t"], row.V_over_t)]
                if fpeps_match.empty:
                    raise ValueError(f"Missing Zhou fPEPS cross-check at V={row.V_over_t}")
                e_fpeps_per_site = float(fpeps_match.iloc[0]["value"])
            e_fpeps_per_particle = (
                e_fpeps_per_site / spinless_density
                if math.isfinite(e_fpeps_per_site)
                else math.nan
            )
            records.append(
                {
                    "comparison": "Zhou_energy",
                    "U_over_t": 0.0,
                    "V_over_t": row.V_over_t,
                    "mmhk_model": "spinful V-extended 16-MMHK",
                    "literature_model": "spinless 10x10-OBC t-V",
                    # Primary comparison values are per particle.  Zhou Table I
                    # reports energy per lattice site at density 1/2, whereas
                    # spinful 16-MMHK is at density one.
                    "mmhk_value": e_spinful_per_particle,
                    "literature_value": e_spinless_per_particle,
                    "mmhk_density_per_site": spinful_density,
                    "spinless_density_per_site": spinless_density,
                    "mmhk_energy_per_site": e_spinful_per_site,
                    "spinless_energy_per_site": e_spinless_per_site,
                    "mmhk_energy_per_particle": e_spinful_per_particle,
                    "spinless_energy_per_particle": e_spinless_per_particle,
                    "fPEPS_energy_per_site": e_fpeps_per_site,
                    "fPEPS_energy_per_particle": e_fpeps_per_particle,
                    "p1_minus_fPEPS_per_site": (
                        e_spinless_per_site - e_fpeps_per_site
                        if math.isfinite(e_fpeps_per_site)
                        else math.nan
                    ),
                    "energy_per_particle_difference": (
                        e_spinful_per_particle - e_spinless_per_particle
                    ),
                    "mmhk_V0_subtracted_per_particle": (
                        e_spinful_per_particle - mmhk_baseline_per_particle
                    ),
                    "spinless_V0_subtracted_per_particle": (
                        e_spinless_per_particle - spinless_baseline_per_particle
                    ),
                    "normalization": (
                        "energy per particle; source energies converted from "
                        "energy per site using the stated density"
                    ),
                    "interpretation": "descriptive model comparison, not an MMHK accuracy error",
                }
            )
    return pd.DataFrame(records)


