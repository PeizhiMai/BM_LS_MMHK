def main() -> None:
    args = parse_args()
    args.results_dir.mkdir(parents=True, exist_ok=True)
    frame = load_rows(args.raw_dir)
    summary = summarize(frame, args.allow_incomplete)
    summary = add_analytic_free_baseline(summary)
    literature = pd.read_csv(args.literature_csv)

    total, per_site = exact_spinless_obc_energy()
    stored = literature[literature["record_id"] == "exact_spinless_10x10_obc_E_V0"].iloc[0]
    if not math.isclose(float(stored["value"]), per_site, abs_tol=1e-14):
        raise ValueError("Stored exact 10x10-OBC V=0 baseline failed recomputation")

    comparison = build_comparisons(summary, literature)
    frame.to_csv(args.results_dir / "zeroT_D_E_mmhk_rows.csv.gz", index=False)
    summary.to_csv(args.results_dir / "zeroT_D_E_mmhk.csv", index=False)
    comparison.to_csv(args.results_dir / "zeroT_D_E_comparison.csv", index=False)

    manifest = {
        "raw_dir": str(args.raw_dir.resolve()),
        "literature_csv": str(args.literature_csv.resolve()),
        "raw_file_count": int(len(frame)),
        "calculated_interaction_set_count": len(CALCULATED_SETS),
        "analytic_interaction_set_count": 1,
        "comparison_interaction_set_count": int(len(summary[summary["status"] == "COMPLETE"])),
        "all_sets_complete": bool((summary["status"] == "COMPLETE").all()),
        "expected_total_raw_files": len(CALCULATED_SETS) * EXPECTED_ROWS,
        "expected_rows_per_set": EXPECTED_ROWS,
        "expected_quadrature_weight": EXPECTED_WEIGHT,
        "energy_plot_normalization": "energy per particle E0/Ne",
        "spinful_density_per_site": 1.0,
        "zhou_spinless_density_per_site": 0.5,
        "zhou_reported_energy_normalization": "energy per lattice site",
        "zhou_per_particle_conversion": "(E0/Ns)/(Ne/Ns) = 2(E0/Ns)",
        "exact_spinless_10x10_obc_V0_total": total,
        "exact_spinless_10x10_obc_V0_per_site": per_site,
        "exact_free_16mmhk_41_grid_E0_per_site": exact_free_16mmhk_grid_energy(1),
        "exact_free_16mmhk_21_grid_E0_per_site": exact_free_16mmhk_grid_energy(2),
        "exact_free_16mmhk_11_grid_E0_per_site": exact_free_16mmhk_grid_energy(4),
        "free_spinful_thermodynamic_E0_per_site": -16.0 / math.pi**2,
        "free_spinless_thermodynamic_E0_per_site": -8.0 / math.pi**2,
    }
    (args.results_dir / "zeroT_D_E_validation.json").write_text(json.dumps(manifest, indent=2) + "\n")

    if manifest["all_sets_complete"]:
        free = summary[np.isclose(summary["U_over_t"], 0.0) & np.isclose(summary["V_over_t"], 0.0)].iloc[0]
        if not math.isclose(float(free["D_mean"]), 0.25, abs_tol=1e-8):
            raise ValueError(f"Free-limit D check failed: {free['D_mean']}")
        if abs(float(free["E0_per_site_mean"]) - manifest["exact_free_16mmhk_41_grid_E0_per_site"]) > 1e-9:
            raise ValueError(f"Free-limit energy check failed: {free['E0_per_site_mean']}")
        make_figure(
            summary,
            literature,
            args.figures_dir / "zeroT_D_E_benchmark",
        )
        write_note(
            args.notes_dir / "2026-08-19_zeroT_D_E_literature_comparison.md",
            summary,
            comparison,
            args.raw_dir,
            args.literature_csv,
        )
    elif not args.allow_incomplete:
        raise RuntimeError("Incomplete data unexpectedly reached output stage")

    print(summary.to_string(index=False))
    print(f"Exact spinless 10x10-OBC V=0: E0={total:.15f}, E0/Ns={per_site:.15f}")


if __name__ == "__main__":
    main()
