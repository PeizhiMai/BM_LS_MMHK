"""Analyze zero-temperature double-occupancy and energy benchmarks.

The script consumes a frozen snapshot of ``*_E0D.dat`` files generated by
``code/Hubbard_sym_E0_D_UV.cc``.  It reconstructs the full mixed-momentum
integral from the symmetry wedge, validates completeness and quadrature, and
compares the resulting 16-MMHK observables with Yao et al. (double occupancy)
and Zhou et al. (spinless t-V energy).
"""

